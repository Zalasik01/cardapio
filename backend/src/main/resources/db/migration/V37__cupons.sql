INSERT INTO s_pagina (guid, id_categoria_menu, nome, rota, ordem, screen)
SELECT gen_random_uuid(), c.id_categoria_menu, 'Cupons', '/admin/cupons', 5, 'Geral, Cupons'
FROM s_categoria_menu c
WHERE c.nome = 'Geral'
  AND NOT EXISTS (SELECT 1 FROM s_pagina x WHERE x.rota = '/admin/cupons');

INSERT INTO s_permissao (guid, codigo, nome, tipo, id_pagina, ordem)
SELECT gen_random_uuid(), v.codigo, v.nome, v.tipo, p.id_pagina, v.ordem
FROM (VALUES
    ('/admin/cupons', 'CUPONS_LEITURA', 'Visualizar os cupons', 'LEITURA', 1),
    ('/admin/cupons', 'CUPONS_ESCRITA', 'Editar os cupons', 'ESCRITA', 2),
    ('/admin/cupons', 'CUPONS_INCLUIR', 'Cadastrar cupom', 'ACAO', 3),
    ('/admin/cupons', 'CUPONS_ALTERAR', 'Alterar cupom', 'ACAO', 4),
    ('/admin/cupons', 'CUPONS_EXCLUIR', 'Excluir cupom', 'ACAO', 5),
    ('/admin/cupons', 'CUPONS_INATIVAR', 'Ativar e inativar cupons', 'ACAO', 6)
) AS v (rota, codigo, nome, tipo, ordem)
JOIN s_pagina p ON p.rota = v.rota
WHERE NOT EXISTS (SELECT 1 FROM s_permissao x WHERE x.codigo = v.codigo);
