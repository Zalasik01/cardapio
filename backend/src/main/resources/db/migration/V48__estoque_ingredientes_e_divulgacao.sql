INSERT INTO s_permissao (guid, codigo, nome, tipo, id_pagina, ordem)
SELECT gen_random_uuid(), v.codigo, v.nome, v.tipo, p.id_pagina, v.ordem
FROM (VALUES
    ('/admin/estoque', 'ESTOQUE_LEITURA', 'Visualizar o estoque de ingredientes', 'LEITURA', 1),
    ('/admin/estoque', 'ESTOQUE_ESCRITA', 'Lançar movimentos de estoque', 'ESCRITA', 2),
    ('/admin/estoque', 'ESTOQUE_ALTERAR', 'Alterar controle e mínimo do estoque', 'ACAO', 3),
    ('/admin/divulgacao', 'DIVULGACAO_LEITURA', 'Visualizar o material de divulgação', 'LEITURA', 1)
) AS v (rota, codigo, nome, tipo, ordem)
JOIN s_pagina p ON p.rota = v.rota
WHERE NOT EXISTS (SELECT 1 FROM s_permissao x WHERE x.codigo = v.codigo);
