FROM (VALUES
    ('/admin/fidelidade', 'FIDELIDADE_LEITURA', 'Visualizar o programa de fidelidade', 'LEITURA', 1),
    ('/admin/fidelidade', 'FIDELIDADE_ESCRITA', 'Editar o programa de fidelidade', 'ESCRITA', 2),
