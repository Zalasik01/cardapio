       'Geral, Produtos, Produtos finais'
FROM s_pagina p
JOIN s_categoria_menu c ON c.id_categoria_menu = p.id_categoria_menu AND c.nome = 'Geral'
WHERE p.nome = 'Produtos' AND p.rota IS NULL
  AND NOT EXISTS (SELECT 1 FROM s_pagina x WHERE x.rota = '/admin/produtos-finais');

