INSERT INTO s_pagina (guid, id_categoria_menu, nome, rota, ordem, screen)
SELECT gen_random_uuid(), c.id_categoria_menu, 'Fluxo de pedidos', '/admin/fluxo-pedidos', 2, 'Loja, Fluxo de pedidos'
FROM s_categoria_menu c
WHERE c.nome = 'Loja'
  AND NOT EXISTS (SELECT 1 FROM s_pagina x WHERE x.rota = '/admin/fluxo-pedidos');

INSERT INTO s_permissao (guid, codigo, nome, tipo, id_pagina, ordem)
SELECT gen_random_uuid(), v.codigo, v.nome, v.tipo, p.id_pagina, v.ordem
FROM (VALUES
    ('FLUXO_PEDIDOS_LEITURA', 'Visualizar o fluxo de pedidos', 'LEITURA', 1),
    ('FLUXO_PEDIDOS_ESCRITA', 'Editar o fluxo de pedidos', 'ESCRITA', 2),
    ('FLUXO_PEDIDOS_ALTERAR', 'Configurar situações e transições do fluxo', 'ACAO', 3)
) AS v (codigo, nome, tipo, ordem)
JOIN s_pagina p ON p.rota = '/admin/fluxo-pedidos'
WHERE NOT EXISTS (SELECT 1 FROM s_permissao x WHERE x.codigo = v.codigo);
